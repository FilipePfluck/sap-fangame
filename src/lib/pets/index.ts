function stripTooltipNotes(text: string): string {
  return text
    .replace(/\s*\(\s*(?:Level up reward|Level-up reward|Note|Notes)\s*[:\-]?[\s\S]*?\)\s*/gi, " ")
    .replace(/\s*(?:\r?\n)\s*(?:Note|Notes)\s*:\s*[\s\S]*$/gi, "")
    .replace(/\s*(?:\r?\n)\s*(?:Note|Notes)\s*[-:]\s*[\s\S]*$/gi, "")
    .replace(/\s*(?:\r?\n)\s*(?:Similar targeting to|Like|Equivalent to|Comparable to)\s+[\s\S]*$/gi, "")
    .replace(/\s*\b(?:Similar targeting to|Like|Equivalent to|Comparable to)\s+[A-Z][\w\s-]*\.?\s*$/gi, "")
    .trim();
}

function getPetDescription(pet: StaticPet | undefined, level: number): string | undefined {
  if (!pet) return undefined;
  const description = typeof pet.description === "function" ? pet.description(level) : pet.description;
  return description ? stripTooltipNotes(description) : undefined;
}

export function getPetTooltipText(pet: StaticPet | undefined, level: number): string {
  const description = getPetDescription(pet, level);
  return pet && description ? `${pet.name}\n${description}` : "";
}

export function getAllLevelsTooltipText(pet: StaticPet): string {
  const levelLines = Array.from({ length: MAX_PET_LEVEL }, (_, index) => {
    const level = index + 1;
    return `L${level} ${getPetDescription(pet, level) ?? ""}`;
  });
  return [`${pet.name} ${pet.baseAttack}/${pet.baseHealth}`, ...levelLines].join("\n");
}
